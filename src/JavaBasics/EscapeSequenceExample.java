package JavaBasics;

/*
  Escape Sequences

  \n  -> New Line
  \t  -> Tab Space
  \"  -> Double Quote
  \'  -> Single Quote
  \\  -> Backslash

 */

public class EscapeSequenceExample {
    public static void main(String[] args) {

        System.out.println("Java\nDeveloper");

        System.out.println();

        System.out.println("Name\tAge\tCity");
        System.out.println("Bhavesh\t22\tWardha");

        System.out.println();

        System.out.println("\"Learning Java\"");

        System.out.println();

        System.out.println("C:\\Program Files\\Java");
    }
}